#!/bin/bash
# Script maître : on enchaîne toutes les étapes et on demande si on purge au début
set -e  # on stoppe si une commande échoue

echo "===================   Script maître TP4  ====================="
echo " "
echo "=============================================================="
read -p "Voudriez-vous lancer la purge Docker avant ? (o/n) " choix
echo "=============================================================="
echo " "
if [ "$choix" = "o" ] || [ "$choix" = "O" ]; then
  echo "=============================================================="
  echo " [1/7]    Purge Docker"
  echo "=============================================================="
  ./purge.sh
else
  echo "=============================================================="
  echo " [1/7]    Purge ignorée"
  echo "=============================================================="
fi
echo " "


echo "=============================================================="
echo " [2/7]    Création du réseau"
echo "=============================================================="
./create_network.sh
echo " "


echo "=============================================================="
echo " [3/7]    Lancement MySQL (port 3307 -> 3306)"
echo "=============================================================="
./run_mysql.sh
echo " "
echo "   …on laisse MySQL démarrer (5s)"
sleep 5
echo " "


echo "=============================================================="
echo " [4/7]    Remplissage de la base (data.sql)"
echo "=============================================================="
./filldb.sh
echo " "


echo "=============================================================="
echo " [5/7]    Build de l'image Flask"
echo "=============================================================="
./build_image.sh
echo " "


echo "=============================================================="
echo " [6/7]    Lancement de l'appli Flask"
echo "=============================================================="
./run_app.sh
echo " "


echo "=============================================================="
echo " [7/7]    Terminé. Conteneurs actifs :"
echo "=============================================================="
docker ps
echo " "


echo "=============================================================="
echo " Ouvrez    http://localhost:5000    dans un navigateur"
echo "=============================================================="